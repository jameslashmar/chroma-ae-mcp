#!/usr/bin/env node
// Syncs the motion-director guidance into the repo and regenerates the TS module.
//
//   node scripts/sync-guidance.mjs
//
// 1. If the skill source folder exists (~/.claude/skills/chroma-motion-director, or the
//    path in CHROMA_MOTION_SKILL_DIR), copies SKILL.md, NOTICE.md and references/*.md into
//    server/guidance/motion-director/. Otherwise it keeps the committed copy and says so.
// 2. Regenerates server/src/guidance/content.generated.ts from server/guidance/ so the
//    text ships inside both the tsc build and the esbuild bundle (no runtime file reads).
// No network. server/test/guidance.test.ts fails if the generated module drifts.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dest = path.join(root, "server", "guidance", "motion-director");
const out = path.join(root, "server", "src", "guidance", "content.generated.ts");
const src =
  process.env.CHROMA_MOTION_SKILL_DIR ||
  path.join(os.homedir(), ".claude", "skills", "chroma-motion-director");

const norm = (s) => s.replace(/\r\n/g, "\n");

function listMd(dir, prefix = "") {
  const found = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) found.push(...listMd(path.join(dir, e.name), rel));
    else if (e.name.endsWith(".md")) found.push(rel);
  }
  return found.sort();
}

if (fs.existsSync(path.join(src, "SKILL.md"))) {
  const rels = listMd(src).filter(
    (r) => r === "SKILL.md" || r === "NOTICE.md" || r.startsWith("references/")
  );
  fs.rmSync(dest, { recursive: true, force: true });
  for (const rel of rels) {
    const to = path.join(dest, rel);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, norm(fs.readFileSync(path.join(src, rel), "utf8")));
  }
  console.log(`Copied ${rels.length} files from ${src}`);
} else if (fs.existsSync(path.join(dest, "SKILL.md"))) {
  console.log(`Skill source not found at ${src}; keeping the committed copy in server/guidance/.`);
} else {
  console.error(`No skill source at ${src} and no committed copy in ${dest}. Nothing to do.`);
  process.exit(1);
}

const files = listMd(dest);
let ts =
  "// GENERATED by scripts/sync-guidance.mjs from server/guidance/motion-director/. Do not edit.\n" +
  "// Shipped as strings so it works in the tsc build and in the esbuild panel bundle.\n" +
  "export const GUIDANCE_FILES: Record<string, string> = {\n";
for (const rel of files) {
  ts += `  ${JSON.stringify(rel)}: ${JSON.stringify(norm(fs.readFileSync(path.join(dest, rel), "utf8")))},\n`;
}
ts += "};\n";
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, ts);
console.log(`Wrote ${path.relative(root, out)} (${files.length} files)`);
